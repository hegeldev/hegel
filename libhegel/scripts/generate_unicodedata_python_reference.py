#!/usr/bin/env python3
"""Generate independent Python-sourced reference tables for testing.

Run from anywhere, with uv on the path:

    python3 libhegel/scripts/generate_unicodedata_python_reference.py

For each Unicode version the engine has tables for (the `UNICODE_VERSION`
and `OLDER_VERSIONS` of `generate_unicodedata_tables.py`) this runs
`unicodedata.category()` over every codepoint under a CPython whose
`unicodedata` is that version (uv fetches the interpreters in PYTHONS;
each CPython minor ships one Unicode version), and emits:

  - `libhegel/tests/embedded/native/unicodedata_python_reference_data.rs`:
    a run-length-encoded list of `(end_codepoint, category_str)` pairs for
    UNICODE_VERSION.
  - `libhegel/tests/embedded/native/unicodedata_python_reference_deltas.rs`:
    for each older version, newest first, the `(start, end, category_str)`
    runs of the codepoints whose category differs from the next newer
    version's.

The Rust tests compare `UnicodeVersion::general_category` against these for
every codepoint in `0..=0x10FFFF` and every version, catching any
divergence between the engine's tables (the vendored UnicodeData.txt and
the generated deltas) and Python's own tables for that version.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_unicodedata_tables import OLDER_VERSIONS, UNICODE_VERSION  # noqa: E402

LIBHEGEL = Path(__file__).resolve().parent.parent
TESTS = LIBHEGEL / "tests" / "embedded" / "native"
DATA_PATH = TESTS / "unicodedata_python_reference_data.rs"
DELTAS_PATH = TESTS / "unicodedata_python_reference_deltas.rs"

MAX_CP = 0x10FFFF

# The CPython minors whose `unicodedata` between them cover every version
# the engine has tables for.
PYTHONS = ["3.11", "3.12", "3.13", "3.14", "3.15"]

# Prints the interpreter's Unicode version, then the category of each
# codepoint on its own line.
DUMP = """
import sys
import unicodedata
print(unicodedata.unidata_version)
sys.stdout.writelines(f"{unicodedata.category(chr(cp))}\\n" for cp in range(0x110000))
"""


def python_categories() -> dict[str, list[str]]:
    """The category of every codepoint, indexed by codepoint, according to
    the `unicodedata` of each of PYTHONS, keyed by its Unicode version."""
    tables: dict[str, list[str]] = {}
    for python in PYTHONS:
        result = subprocess.run(
            ["uv", "run", "--no-project", "--python", python, "python", "-c", DUMP],
            check=True,
            capture_output=True,
            text=True,
        )
        version, *categories = result.stdout.splitlines()
        assert len(categories) == MAX_CP + 1, len(categories)
        print(f"Python {python} is Unicode {version}.")
        tables[version] = categories
    return tables


def runs(categories: list[str]) -> list[tuple[int, int, str]]:
    out: list[tuple[int, int, str]] = []
    for cp, cat in enumerate(categories):
        if out and out[-1][2] == cat and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp, cat)
        else:
            out.append((cp, cp, cat))
    return out


def delta(older: list[str], newer: list[str]) -> list[tuple[int, int, str]]:
    out: list[tuple[int, int, str]] = []
    for cp, (old, new) in enumerate(zip(older, newer)):
        if old == new:
            continue
        if out and out[-1][2] == old and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp, old)
        else:
            out.append((cp, cp, old))
    return out


HEADER = [
    "// Auto-generated by scripts/generate_unicodedata_python_reference.py.",
    "// Do not edit by hand; regenerate when upgrading the Unicode tables.",
]


def write_data(categories: list[str]) -> int:
    ranges = runs(categories)
    lines = HEADER + [
        f"// Source: unicodedata.category() of a CPython with Unicode {UNICODE_VERSION}.",
        "// Run-length-encoded: each tuple is (end_inclusive, category_code),",
        "// covering `0..=0x10FFFF` contiguously.",
        "[",
    ]
    lines += [f'    ({end:#07x}, "{cat}"),' for _, end, cat in ranges]
    lines += ["]", ""]
    DATA_PATH.write_text("\n".join(lines))
    return len(ranges)


def write_deltas(deltas: list[tuple[str, list[tuple[int, int, str]]]]) -> None:
    lines = HEADER + [
        "// Source: unicodedata.category() of a CPython with each Unicode version.",
        "// Each entry is a Unicode version older than the engine's latest, newest",
        "// first, with the (start, end, category_code) runs of the codepoints whose",
        "// category differs from the next newer version's.",
        "[",
    ]
    for version, ranges in deltas:
        lines.append(f'    ("{version}", &[')
        lines += [f'        ({start:#07x}, {end:#07x}, "{cat}"),' for start, end, cat in ranges]
        lines.append("    ]),")
    lines += ["]", ""]
    DELTAS_PATH.write_text("\n".join(lines))


def main() -> None:
    tables = python_categories()
    missing = [v for v in [UNICODE_VERSION, *OLDER_VERSIONS] if v not in tables]
    if missing:
        sys.exit(f"no Python in {PYTHONS} has Unicode {', '.join(missing)}")
    newer = tables[UNICODE_VERSION]
    count = write_data(newer)
    print(f"Wrote {DATA_PATH} with {count} ranges (Unicode {UNICODE_VERSION}).")
    deltas = []
    for version in OLDER_VERSIONS:
        older = tables[version]
        deltas.append((version, delta(older, newer)))
        print(f"Unicode {version}: {len(deltas[-1][1])} runs differ from the next version.")
        newer = older
    write_deltas(deltas)
    print(f"Wrote {DELTAS_PATH}.")


if __name__ == "__main__":
    main()
