// The in-tree libhegel engine this frontend is built and tested against: the
// `hegeltest-c` crate in `libhegel/`, compiled natively (for koffi) and to
// `wasm32-unknown-unknown` (for the browser entry) by `just typescript::build-libhegel`
// into the workspace's `target/` directory. `HEGEL_LIBHEGEL_PATH` and
// `HEGEL_WASM_PATH` override the two locations, and `CARGO_TARGET_DIR` moves
// the whole target directory, as it does for cargo.
//
// The engine version the package ships is `libhegel/Cargo.toml`'s; the
// generated `src/libhegel-version.ts` mirrors it for the runtime version checks
// and the release automation keeps the two in step.
//
// Usage:
//   node scripts/engine.mjs native         # print the native library's path
//   node scripts/engine.mjs wasm [<dir>]   # print the Wasm module's path, copying it into <dir> first if given
//   node scripts/engine.mjs version        # print libhegel's version
//   node scripts/engine.mjs write-version  # regenerate src/libhegel-version.ts
//   node scripts/engine.mjs check-version  # fail if src/libhegel-version.ts is stale

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MONOREPO = path.resolve(ROOT, "..", "..");
const CARGO_TOML = path.join(MONOREPO, "libhegel", "Cargo.toml");
const VERSION_TS = path.join(ROOT, "src", "libhegel-version.ts");

/** The Wasm module's filename in `dist/browser/` (see src/browser/artifact.ts). */
export const WASM_ASSET = "libhegel-wasm32-unknown-unknown.wasm";

const NATIVE_LIBRARIES = {
  darwin: "libhegel_c.dylib",
  linux: "libhegel_c.so",
  win32: "hegel_c.dll",
};

function targetDir() {
  return process.env.CARGO_TARGET_DIR ?? path.join(MONOREPO, "target");
}

function built(override, candidate, what) {
  const location = process.env[override] || candidate;
  if (!fs.existsSync(location)) {
    throw new Error(
      `${what} not found at ${location}; run \`just typescript::build-libhegel\` or set ${override}`,
    );
  }
  return location;
}

/** The release build of libhegel for the host, as a shared library. */
export function nativeLibraryPath() {
  const library = NATIVE_LIBRARIES[process.platform];
  if (library === undefined) {
    throw new Error(`unsupported host ${process.platform} for libhegel`);
  }
  return built("HEGEL_LIBHEGEL_PATH", path.join(targetDir(), "release", library), "libhegel");
}

/** The release build of libhegel for wasm32-unknown-unknown. */
export function wasmPath() {
  return built(
    "HEGEL_WASM_PATH",
    path.join(targetDir(), "wasm32-unknown-unknown", "release", "hegel_c.wasm"),
    "the libhegel Wasm module",
  );
}

/** libhegel's version, from its Cargo manifest. */
export function libhegelVersion() {
  const match = /^version = "([^"]+)"$/m.exec(fs.readFileSync(CARGO_TOML, "utf8"));
  if (!match) {
    throw new Error(`could not find the package version in ${CARGO_TOML}`);
  }
  return match[1];
}

function versionSource() {
  return (
    "// Generated by scripts/engine.mjs from libhegel/Cargo.toml. Do not edit.\n" +
    `export const LIBHEGEL_VERSION = "${libhegelVersion()}";\n`
  );
}

function main(args) {
  const [command, ...rest] = args;
  const expectArguments = (count) => {
    if (rest.length !== count) {
      throw new Error(
        "usage: engine.mjs native | wasm [<dir>] | version | write-version | check-version",
      );
    }
  };
  switch (command) {
    case "native":
      expectArguments(0);
      return `${nativeLibraryPath()}\n`;
    case "wasm": {
      if (rest.length > 1) expectArguments(1);
      let location = wasmPath();
      if (rest[0] !== undefined) {
        fs.mkdirSync(rest[0], { recursive: true });
        const copy = path.join(rest[0], WASM_ASSET);
        fs.copyFileSync(location, copy);
        location = copy;
      }
      return `${location}\n`;
    }
    case "version":
      expectArguments(0);
      return `${libhegelVersion()}\n`;
    case "write-version":
      expectArguments(0);
      fs.writeFileSync(VERSION_TS, versionSource());
      return "";
    case "check-version": {
      expectArguments(0);
      const current = fs.existsSync(VERSION_TS) ? fs.readFileSync(VERSION_TS, "utf8") : "";
      if (current !== versionSource()) {
        throw new Error(
          "src/libhegel-version.ts does not match libhegel/Cargo.toml; " +
            "run `node scripts/engine.mjs write-version`",
        );
      }
      return "";
    }
    default:
      expectArguments(-1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    process.stdout.write(main(process.argv.slice(2)));
  } catch (err) {
    process.stderr.write(`${err.message ?? err}\n`);
    process.exit(1);
  }
}
