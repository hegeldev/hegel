// Checks on the packaging scripts that need no network: checksum sidecar
// parsing, the conditional export map, the generated engine version pin, and
// the platform packages assembled from the in-tree build. `just
// typescript::check-browser` covers the packed package.
import assert from "node:assert/strict";
import { test } from "node:test";
import { execFileSync, spawnSync } from "node:child_process";
import * as fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { PLATFORMS, hostPlatform, sha256, sidecarDigest } from "./fetch-libhegel.mjs";
import { WASM_ASSET, libhegelVersion, nativeLibraryPath } from "./engine.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

test("checksum sidecars are parsed strictly", () => {
  const hex = "c".repeat(64);
  assert.equal(sidecarDigest(`${hex}  ${WASM_ASSET}\n`, WASM_ASSET), hex);
  assert.equal(sidecarDigest(`${hex} *${WASM_ASSET}`, WASM_ASSET), hex);
  assert.equal(sidecarDigest(hex, WASM_ASSET), hex);
  assert.throws(() => sidecarDigest(`${hex}  other.wasm`, WASM_ASSET), /malformed/);
  assert.throws(() => sidecarDigest(`${hex.slice(1)}  ${WASM_ASSET}`, WASM_ASSET), /malformed/);
  assert.throws(() => sidecarDigest("garbage", WASM_ASSET), /malformed/);
  assert.equal(
    sha256(Buffer.alloc(0)),
    "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
  );
});

test("conditional exports keep node ahead of browser and default to browser", () => {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json")));
  assert.deepEqual(Object.keys(pkg.exports["."]), ["types", "node", "browser", "default"]);
  assert.equal(pkg.exports["."].default, pkg.exports["."].browser);
  assert.notEqual(pkg.exports["."].node, pkg.exports["."].browser);
  assert.equal(pkg.exports["./libhegel.wasm"], `./dist/browser/${WASM_ASSET}`);
  const resolved = execFileSync(
    "node",
    [
      "--conditions=browser",
      "--input-type=module",
      "-e",
      "console.log(import.meta.resolve('@hegeldev/hegel'))",
    ],
    { cwd: ROOT, encoding: "utf8" },
  );
  assert(
    resolved.trim().endsWith("/dist/index.js"),
    "Node must win even when browser is also enabled",
  );
});

// A copy of the frontend's scripts and manifest inside a fake monorepo, so the
// scripts can rewrite files without touching the real tree.
function fakeMonorepo() {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "hegel-typescript-packaging-test-"));
  const frontend = path.join(temp, "frontends", "typescript");
  for (const file of [
    "scripts/engine.mjs",
    "scripts/fetch-libhegel.mjs",
    "scripts/make-platform-packages.mjs",
    "src/libhegel-version.ts",
    "package.json",
  ]) {
    const dest = path.join(frontend, file);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(ROOT, file), dest);
  }
  fs.mkdirSync(path.join(temp, "libhegel"));
  fs.writeFileSync(
    path.join(temp, "libhegel", "Cargo.toml"),
    '[package]\nname = "hegeltest-c"\nversion = "9.9.9"\n\n[dependencies]\nfoo = { version = "1" }\n',
  );
  const run = (script, args, env = {}) =>
    spawnSync(process.execPath, [`scripts/${script}`, ...args], {
      cwd: frontend,
      encoding: "utf8",
      env: { ...process.env, ...env },
    });
  return { temp, frontend, run };
}

test("the engine version pin is generated from libhegel's manifest and checked", () => {
  assert.equal(
    spawnSync(process.execPath, ["scripts/engine.mjs", "check-version"], { cwd: ROOT }).status,
    0,
    "the committed pin must match libhegel/Cargo.toml",
  );
  assert.match(libhegelVersion(), /^\d+\.\d+\.\d+$/);
  const { temp, frontend, run } = fakeMonorepo();
  try {
    assert.equal(run("engine.mjs", ["version"]).stdout, "9.9.9\n");
    const stale = run("engine.mjs", ["check-version"]);
    assert.equal(stale.status, 1);
    assert.match(stale.stderr, /does not match libhegel\/Cargo.toml/);
    assert.equal(run("engine.mjs", ["write-version"]).status, 0);
    assert.equal(
      fs.readFileSync(path.join(frontend, "src/libhegel-version.ts"), "utf8"),
      "// Generated by scripts/engine.mjs from libhegel/Cargo.toml. Do not edit.\n" +
        'export const LIBHEGEL_VERSION = "9.9.9";\n',
    );
    assert.equal(run("engine.mjs", ["check-version"]).status, 0);
    assert.match(run("engine.mjs", ["bogus"]).stderr, /usage/);
    assert.match(run("engine.mjs", ["native", "extra"]).stderr, /usage/);
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
});

test("platform packages are assembled from the in-tree build and pinned on request", () => {
  const { temp, frontend, run } = fakeMonorepo();
  try {
    const missing = run("engine.mjs", ["native"], {
      HEGEL_LIBHEGEL_PATH: "",
      CARGO_TARGET_DIR: temp,
    });
    assert.equal(missing.status, 1);
    assert.match(missing.stderr, /just typescript::build-libhegel/);
    const library = nativeLibraryPath();
    assert.equal(
      run("engine.mjs", ["native"], { HEGEL_LIBHEGEL_PATH: library }).stdout,
      `${library}\n`,
    );
    assert.match(run("make-platform-packages.mjs", ["--bogus"]).stderr, /unknown arguments/);

    const result = run("make-platform-packages.mjs", ["--local", "--pin"], {
      HEGEL_LIBHEGEL_PATH: library,
    });
    assert.equal(result.status, 0, result.stderr);
    const host = hostPlatform();
    const dir = path.join(frontend, "platform-packages", `hegel-${host.platform}-${host.arch}`);
    assert(fs.readFileSync(path.join(dir, host.asset)).equals(fs.readFileSync(library)));
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const root = JSON.parse(fs.readFileSync(path.join(frontend, "package.json"), "utf8"));
    assert.equal(manifest.name, `@hegeldev/hegel-${host.platform}-${host.arch}`);
    assert.equal(manifest.version, root.version);
    assert.deepEqual(manifest.os, [host.platform]);
    assert.deepEqual(manifest.cpu, [host.arch]);
    assert.deepEqual(manifest.exports, { "./binary": `./${host.asset}` });
    assert.deepEqual(
      root.optionalDependencies,
      Object.fromEntries(
        PLATFORMS.map((p) => [`@hegeldev/hegel-${p.platform}-${p.arch}`, root.version]).sort(),
      ),
    );
    assert.equal(
      JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")).optionalDependencies,
      undefined,
      "pins are injected at publish time, never committed",
    );
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
});
