use std::fmt::Write;

fn main() {
    let escaped = |c: char| {
        (c as u32) >= 0x80 && format!("{:?}", format!("a{c}")).contains("\\u{")
    };
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for c in (0x80u32..=0x10FFFF).filter_map(char::from_u32) {
        if escaped(c) {
            let cp = c as u32;
            match ranges.last_mut() {
                Some(last) if last.1 + 1 == cp => last.1 = cp,
                _ => ranges.push((cp, cp)),
            }
        }
    }
    let mut packed = String::new();
    for (i, (lo, hi)) in ranges.iter().enumerate() {
        if i % 4 == 0 {
            packed.push_str("\\\n   ");
        }
        for cp in [lo, hi] {
            for shift in [16, 8, 0] {
                write!(packed, "\\x{:02x}", (cp >> shift) & 0xff).unwrap();
            }
        }
    }
    print!(
        "(* Generated by scripts/gen-unicode-escapes.rs: the code points above \
         U+007F that Rust's Debug escapes. *)\n\n\
         let ranges =\n  \"{packed}\"\n;;\n"
    );
}
