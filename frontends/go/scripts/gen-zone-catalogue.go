//go:build ignore

// Command gen-zone-catalogue writes zone_catalogue.go: the names of the
// engine's bundled time zone catalogue, in rank order.
//
// libhegel's C ABI has no function that lists a zone source's names, and
// neither has Go's time package, so the host zone source declares this list
// and keeps the names time.LoadLocation can load. The list is read from the
// in-tree engine's libhegel/src/tzdata/tzdata.txt, so it is regenerated
// whenever that file changes (TestZoneCatalogueMatchesTheEngine fails until it
// is).
//
// Usage, from frontends/go:
//
//	go run scripts/gen-zone-catalogue.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	tzdataPath = "../../libhegel/src/tzdata/tzdata.txt"
	outputPath = "zone_catalogue.go"
)

type entry struct {
	name string
	rank int
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-zone-catalogue:", err)
		os.Exit(1)
	}
}

func run() error {
	in, err := os.Open(tzdataPath)
	if err != nil {
		return err
	}
	defer in.Close()

	var entries []entry
	version := ""
	scanner := bufio.NewScanner(in)
	scanner.Buffer(make([]byte, 0, 1<<20), 1<<26)
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) == 0 {
			continue
		}
		rankField := -1
		switch fields[0] {
		case "V":
			version = fields[1]
		case "Z":
			rankField = 2
		case "L":
			rankField = 3
		}
		if rankField < 0 {
			continue
		}
		rank, err := strconv.Atoi(fields[rankField])
		if err != nil {
			return fmt.Errorf("rank of %s: %w", fields[1], err)
		}
		entries = append(entries, entry{name: fields[1], rank: rank})
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].rank < entries[j].rank })
	for i, e := range entries {
		if e.rank != i {
			return fmt.Errorf("%s has rank %d at position %d: the ranks are not dense", e.name, e.rank, i)
		}
	}

	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by scripts/gen-zone-catalogue.go; DO NOT EDIT.")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "package hegel")
	fmt.Fprintln(&buf)
	fmt.Fprintf(&buf, "// zoneCatalogue holds the names of the engine's bundled time zone catalogue\n")
	fmt.Fprintf(&buf, "// (IANA %s), each at the index that is its rank.\n", version)
	fmt.Fprintln(&buf, "var zoneCatalogue = [...]string{")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t%q,\n", e.name)
	}
	fmt.Fprintln(&buf, "}")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(outputPath, src, 0o644)
}
