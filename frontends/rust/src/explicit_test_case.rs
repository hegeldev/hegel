use std::any::Any;
use std::cell::RefCell;
use std::collections::HashMap;
use std::fmt::Debug;
use std::panic::{AssertUnwindSafe, catch_unwind, resume_unwind};

use crate::control::{AssumeFailed, LoopDone, raise_control};
use crate::generators::Generator;

struct ExplicitValue {
    source_expr: String,
    value: Option<Box<dyn Any>>,
    debug_repr: String,
}

/// A test case with pre-defined values for explicit/example-based testing.
///
/// Created by `#[hegel::explicit_test_case]`. Values are looked up by the
/// name a draw would be reported under in a failing test case (`x` for
/// `let x = tc.draw(..)`, `x_1`, `x_2`, ... for a draw that can run more
/// than once, `draw_1`, `draw_2`, ... for an unnamed draw), instead of
/// being generated by the engine.
///
/// # Threading
///
/// Unlike [`TestCase`](crate::TestCase), `ExplicitTestCase` is neither `Send`
/// nor `Sync` and does not currently support being used from multiple
/// threads. A test body that clones `tc` and moves it into a spawned thread
/// therefore cannot be combined with `#[hegel::explicit_test_case]`: the
/// macro expands the body with `tc: &ExplicitTestCase` for the explicit run,
/// and `&ExplicitTestCase` will not pass `std::thread::spawn`'s `Send` bound.
pub struct ExplicitTestCase {
    values: RefCell<HashMap<String, ExplicitValue>>,
    draw_counts: RefCell<HashMap<String, usize>>,
    notes: RefCell<Vec<String>>,
}

impl ExplicitTestCase {
    #[doc(hidden)]
    pub fn new() -> Self {
        ExplicitTestCase {
            values: RefCell::new(HashMap::new()),
            draw_counts: RefCell::new(HashMap::new()),
            notes: RefCell::new(Vec::new()),
        }
    }

    #[doc(hidden)]
    pub fn with_value<T: Any + Debug>(self, name: &str, source_expr: &str, value: T) -> Self {
        let debug_repr = format!("{:?}", value);
        self.values.borrow_mut().insert(
            name.to_string(),
            ExplicitValue {
                source_expr: source_expr.to_string(),
                value: Some(Box::new(value)),
                debug_repr,
            },
        );
        self
    }

    pub fn draw<T: Debug + 'static>(&self, generator: impl Generator<T>) -> T {
        self.__draw_named(generator, "draw", true)
    }

    /// The explicit value given for `name`, like
    /// [`TestCase::draw_named`](crate::TestCase::draw_named).
    pub fn draw_named<T: Debug + 'static>(&self, name: &str, generator: impl Generator<T>) -> T {
        self.__draw_named(generator, name, true)
    }

    pub fn __draw_named<T: Debug + 'static>(
        &self,
        _generator: impl Generator<T>,
        name: &str,
        repeatable: bool,
    ) -> T {
        let name = &if repeatable {
            let mut counts = self.draw_counts.borrow_mut();
            let count = counts.entry(name.to_string()).or_insert(0);
            *count += 1;
            format!("{name}_{count}")
        } else {
            name.to_string()
        };
        let mut values = self.values.borrow_mut();
        let entry = match values.get_mut(name) {
            Some(e) => e,
            None => {
                let available: Vec<_> = values.keys().cloned().collect();
                panic!(
                    "Explicit test case: no value provided for {:?}. Available: {:?}",
                    name, available
                );
            }
        };

        let boxed = match entry.value.take() {
            Some(v) => v,
            None => {
                panic!(
                    "Explicit test case: value {:?} was already consumed by a previous draw",
                    name
                );
            }
        };

        let source = &entry.source_expr;
        let debug = &entry.debug_repr;

        let source_normalized: String = source.chars().filter(|c| !c.is_whitespace()).collect();
        let debug_normalized: String = debug.chars().filter(|c| !c.is_whitespace()).collect();

        if source_normalized == debug_normalized {
            crate::test_case::emit_verbose_line(&format!("let {} = {};", name, source));
        } else {
            crate::test_case::emit_verbose_line(&format!(
                "let {} = {}; // = {}",
                name, source, debug
            ));
        }

        match boxed.downcast::<T>() {
            Ok(typed) => *typed,
            Err(_) => panic!(
                "Explicit test case: type mismatch for {:?}. \
                 The value provided in #[hegel::explicit_test_case] \
                 does not match the type expected by draw.",
                name
            ),
        }
    }

    pub fn draw_silent<T>(&self, _generator: impl Generator<T>) -> T {
        panic!("draw_silent is not supported in explicit test cases");
    }

    pub fn note(&self, message: &str) {
        self.notes.borrow_mut().push(message.to_string());
    }

    /// Skip this explicit test case if `condition` is false, like
    /// [`TestCase::assume`](crate::TestCase::assume).
    pub fn assume(&self, condition: bool) {
        if !condition {
            self.reject();
        }
    }

    /// Skip this explicit test case: the rest of the test body does not run,
    /// and the test case neither passes nor fails.
    pub fn reject(&self) -> ! {
        raise_control(AssumeFailed);
    }

    pub fn target(&self, _score: f64) {}

    pub fn target_labelled(&self, _score: f64, _label: impl Into<String>) {}

    /// Does nothing: statistics only count generated test cases.
    pub fn event(&self, _label: impl AsRef<str>) {}

    /// Does nothing: statistics only count generated test cases.
    pub fn event_value(&self, _label: impl AsRef<str>, _value: f64) {}

    /// Run `body` once, then end this explicit test case, like one iteration
    /// of [`TestCase::repeat`](crate::TestCase::repeat). An explicit value
    /// can be drawn only once, so a second iteration would have nothing to
    /// draw. A failed assumption in `body` skips the whole explicit test case.
    pub fn repeat<F: FnMut()>(&self, mut body: F) -> ! {
        self.note("// Repetition #1");
        body();
        raise_control(LoopDone);
    }

    #[doc(hidden)]
    pub fn start_span(&self, _label: u64) {
        panic!("start_span is not supported in explicit test cases");
    }

    #[doc(hidden)]
    pub fn stop_span(&self, _discard: bool) {
        panic!("stop_span is not supported in explicit test cases");
    }

    #[doc(hidden)]
    pub fn run<F: FnOnce(&ExplicitTestCase)>(&self, f: F) {
        let result = catch_unwind(AssertUnwindSafe(|| {
            f(self);
        }));

        match result {
            Err(payload) if payload.downcast_ref::<AssumeFailed>().is_some() => {}
            Err(payload) if payload.downcast_ref::<LoopDone>().is_none() => {
                let notes = self.notes.borrow();
                for note in notes.iter() {
                    crate::test_case::emit_verbose_line(note);
                }
                resume_unwind(payload);
            }
            _ => {
                let values = self.values.borrow();
                let unused: Vec<_> = values
                    .iter()
                    .filter(|(_, v)| v.value.is_some())
                    .map(|(k, _)| k.clone())
                    .collect();
                if !unused.is_empty() {
                    panic!(
                        "Explicit test case: the following values were provided \
                         but never drawn: {:?}",
                        unused
                    );
                }
            }
        }
    }
}
