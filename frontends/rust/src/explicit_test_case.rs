use std::any::Any;
use std::cell::RefCell;
use std::collections::HashMap;
use std::fmt::Debug;
use std::panic::{RefUnwindSafe, UnwindSafe};
use std::rc::Rc;

use crate::control::{LoopDone, hegel_internal_error, raise_control};
use crate::generators::Generator;
use crate::run_lifecycle::{ExplicitFailure, raise_failures, run_explicit_case};
use crate::runner::{Settings, Verbosity};
use crate::test_case::{RunOutput, invalid_argument};

struct ExplicitValue {
    source_expr: String,
    value: Option<Box<dyn Any>>,
    debug_repr: String,
}

/// What every handle of one explicit test case shares: its values, the
/// draw-name bookkeeping, and the lines it has printed, in order.
struct State {
    values: HashMap<String, ExplicitValue>,
    draw_counts: HashMap<String, usize>,
    named_draw_repeatable: HashMap<String, bool>,
    lines: Vec<String>,
}

/// A test case with pre-defined values for explicit/example-based testing.
///
/// Created by `#[hegel::explicit_test_case]`. Values are looked up by the
/// name a draw would be reported under in a failing test case (`x` for
/// `let x = tc.draw(..)`, `x_1`, `x_2`, ... for a draw that can run more
/// than once, `draw_1`, `draw_2`, ... for an unnamed draw), instead of
/// being generated by the engine.
///
/// [`clone`](Clone::clone) returns a handle onto the same explicit test
/// case: a clone draws the same values and names its draws in the same
/// scope as the handle it was cloned from, and [`set_worker`](Self::set_worker)
/// does nothing, as an explicit test case has no output to attribute.
///
/// # Threading
///
/// Unlike [`TestCase`](crate::TestCase), `ExplicitTestCase` is neither `Send`
/// nor `Sync` and does not currently support being used from multiple
/// threads. A test body that clones `tc` and moves it into a spawned thread
/// therefore cannot be combined with `#[hegel::explicit_test_case]`: the
/// macro expands the body with `tc: &ExplicitTestCase` for the explicit run,
/// and `ExplicitTestCase` will not pass `std::thread::spawn`'s `Send` bound.
pub struct ExplicitTestCase {
    state: Rc<RefCell<State>>,
}

impl Clone for ExplicitTestCase {
    fn clone(&self) -> Self {
        ExplicitTestCase {
            state: Rc::clone(&self.state),
        }
    }
}

impl ExplicitTestCase {
    #[doc(hidden)]
    pub fn new() -> Self {
        ExplicitTestCase {
            state: Rc::new(RefCell::new(State {
                values: HashMap::new(),
                draw_counts: HashMap::new(),
                named_draw_repeatable: HashMap::new(),
                lines: Vec::new(),
            })),
        }
    }

    #[doc(hidden)]
    pub fn with_value<T: Any + Debug>(self, name: &str, source_expr: &str, value: T) -> Self {
        let debug_repr = format!("{:?}", value);
        self.state.borrow_mut().values.insert(
            name.to_string(),
            ExplicitValue {
                source_expr: source_expr.to_string(),
                value: Some(Box::new(value)),
                debug_repr,
            },
        );
        self
    }

    pub fn draw<T: Debug + 'static>(&self, generator: impl Generator<T>) -> T {
        self.__draw_named(generator, "draw", true)
    }

    /// The explicit value given for `name`, like
    /// [`TestCase::draw_named`](crate::TestCase::draw_named).
    pub fn draw_named<T: Debug + 'static>(&self, name: &str, generator: impl Generator<T>) -> T {
        self.__draw_named(generator, name, true)
    }

    pub fn __draw_named<T: Debug + 'static>(
        &self,
        _generator: impl Generator<T>,
        name: &str,
        repeatable: bool,
    ) -> T {
        let mut state = self.state.borrow_mut();
        let prev = *state
            .named_draw_repeatable
            .entry(name.to_string())
            .or_insert(repeatable);
        if prev != repeatable {
            hegel_internal_error!(
                "__draw_named: name {:?} used with inconsistent repeatable flag \
                 (was {}, now {})",
                name,
                prev,
                repeatable
            );
        }
        let count = {
            let count = state.draw_counts.entry(name.to_string()).or_insert(0);
            *count += 1;
            *count
        };
        if !repeatable && count > 1 {
            hegel_internal_error!(
                "__draw_named: name {:?} used more than once but repeatable is false",
                name
            );
        }
        let name = &if repeatable {
            format!("{name}_{count}")
        } else {
            name.to_string()
        };
        let (boxed, line) = {
            let entry = match state.values.get_mut(name) {
                Some(e) => e,
                None => {
                    let mut available: Vec<_> = state.values.keys().cloned().collect();
                    available.sort();
                    invalid_argument!(
                        "Explicit test case: no value provided for {:?}. Available: {:?}",
                        name,
                        available
                    );
                }
            };

            let boxed = match entry.value.take() {
                Some(v) => v,
                None => {
                    invalid_argument!(
                        "Explicit test case: value {:?} was already consumed by a previous draw",
                        name
                    );
                }
            };

            let source = &entry.source_expr;
            let debug = &entry.debug_repr;

            let source_normalized: String = source.chars().filter(|c| !c.is_whitespace()).collect();
            let debug_normalized: String = debug.chars().filter(|c| !c.is_whitespace()).collect();

            let line = if source_normalized == debug_normalized {
                format!("let {} = {};", name, source)
            } else {
                format!("let {} = {}; // = {}", name, source, debug)
            };
            (boxed, line)
        };
        state.lines.push(line);

        match boxed.downcast::<T>() {
            Ok(typed) => *typed,
            Err(_) => invalid_argument!(
                "Explicit test case: type mismatch for {:?}. \
                 The value provided in #[hegel::explicit_test_case] \
                 does not match the type expected by draw.",
                name
            ),
        }
    }

    /// A usage error: an explicit test case gives its values by name, and a
    /// silent draw has no name to look one up by.
    pub fn draw_silent<T>(&self, _generator: impl Generator<T>) -> T {
        invalid_argument!("draw_silent is not supported in explicit test cases");
    }

    pub fn note(&self, message: &str) {
        self.state.borrow_mut().lines.push(message.to_string());
    }

    /// Fail with a usage error if `condition` is false: an explicit test
    /// case must not be rejected, so a failed assumption is a mistake in the
    /// test rather than a skipped test case.
    pub fn assume(&self, condition: bool) {
        if !condition {
            self.reject();
        }
    }

    /// Fail with a usage error: an explicit test case must not be rejected,
    /// so rejecting one is a mistake in the test rather than a skipped test
    /// case.
    pub fn reject(&self) -> ! {
        invalid_argument!("Explicit test cases must not be rejected");
    }

    pub fn target(&self, _score: f64) {}

    pub fn target_labelled(&self, _score: f64, _label: impl Into<String>) {}

    /// Does nothing: statistics only count generated test cases.
    pub fn event(&self, _label: impl AsRef<str>) {}

    /// Does nothing: statistics only count generated test cases.
    pub fn event_value(&self, _label: impl AsRef<str>, _value: f64) {}

    /// Does nothing: an explicit test case has no output to attribute to a
    /// worker. See [`TestCase::set_worker`](crate::TestCase::set_worker).
    pub fn set_worker(&self, _index: usize) {}

    /// Run `body` once, then end this explicit test case, like one iteration
    /// of [`TestCase::repeat`](crate::TestCase::repeat). An explicit value
    /// can be drawn only once, so a second iteration would have nothing to
    /// draw.
    pub fn repeat<F: FnMut()>(&self, mut body: F) -> ! {
        self.note("// Repetition #1");
        body();
        raise_control(LoopDone);
    }

    #[doc(hidden)]
    pub fn start_span(&self, _label: u64) {
        invalid_argument!("start_span is not supported in explicit test cases");
    }

    #[doc(hidden)]
    pub fn stop_span(&self, _discard: bool) {
        invalid_argument!("stop_span is not supported in explicit test cases");
    }

    /// The draw and note lines printed so far, in order.
    pub(crate) fn lines(&self) -> Vec<String> {
        self.state.borrow().lines.clone()
    }

    /// The names of the values that no draw has taken, sorted.
    pub(crate) fn unused_values(&self) -> Vec<String> {
        let state = self.state.borrow();
        let mut unused: Vec<_> = state
            .values
            .iter()
            .filter(|(_, v)| v.value.is_some())
            .map(|(k, _)| k.clone())
            .collect();
        unused.sort();
        unused
    }

    /// Run `f` as this explicit test case's body on its own, as a test run
    /// with [`report_multiple_failures`](Settings::report_multiple_failures)
    /// off would: a failure prints its report and re-raises the body's own
    /// panic.
    #[doc(hidden)]
    pub fn run<F: FnOnce(&ExplicitTestCase)>(&self, f: F) {
        let output = RunOutput::resolve();
        if let Some(failure) = run_explicit_case(self, f, Verbosity::Normal, &output) {
            raise_failures(vec![failure.into_reported()], false, &output);
        }
    }
}

/// The explicit phase of a test run, as `#[hegel::test]` and its siblings
/// drive it before the generated phases: each explicit test case runs as it
/// is added with [`case`](Self::case). With
/// [`report_multiple_failures`](Settings::report_multiple_failures) off, the
/// first failing case ends the run there, with its report; with it on,
/// every case runs, the failures are kept by origin, and
/// [`Hegel::run`](crate::Hegel::run) reports them together with the failures
/// the generated phases find.
#[doc(hidden)]
pub struct ExplicitRun {
    verbosity: Verbosity,
    report_multiple_failures: bool,
    output: RunOutput,
    failures: Vec<ExplicitFailure>,
}

/// An `ExplicitRun` only carries failures already caught, so a panic that
/// unwinds past it leaves nothing half-updated: a `Hegel` builder holding
/// one stays as unwind-safe as one without.
impl UnwindSafe for ExplicitRun {}
impl RefUnwindSafe for ExplicitRun {}

impl ExplicitRun {
    pub fn new(settings: &Settings) -> Self {
        ExplicitRun {
            verbosity: settings.verbosity,
            report_multiple_failures: settings.report_multiple_failures,
            output: RunOutput::resolve(),
            failures: Vec::new(),
        }
    }

    /// Run `body` as the body of `case`.
    pub fn case<F: FnOnce(&ExplicitTestCase)>(&mut self, case: ExplicitTestCase, body: F) {
        let Some(failure) = run_explicit_case(&case, body, self.verbosity, &self.output) else {
            return;
        };
        if !self.report_multiple_failures {
            let quiet = self.verbosity == Verbosity::Quiet;
            raise_failures(vec![failure.into_reported()], quiet, &self.output);
        }
        if !self.failures.iter().any(|f| f.origin == failure.origin) {
            self.failures.push(failure);
        }
    }

    pub(crate) fn into_failures(self) -> Vec<ExplicitFailure> {
        self.failures
    }
}
